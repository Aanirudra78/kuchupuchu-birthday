/* Scan assets/photos/ -> write photos-data.js + photos.json
   Supports two groups:  single/  (her)   double/  (both of you)
   Usage: node list-photos.js
   No dependencies. Node 18+. */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const PHOTO_DIR = path.join(ROOT, "assets", "photos");
const OUT_JS = path.join(ROOT, "photos-data.js");
const OUT_JSON = path.join(ROOT, "photos.json");

const EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);
const GROUPS = ["single", "double"];

const natural = (a, b) =>
  a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

function scan(dir, group) {
  const full = path.join(PHOTO_DIR, dir);
  if (!fs.existsSync(full)) return [];
  return fs
    .readdirSync(full)
    .filter((f) => EXT.has(path.extname(f).toLowerCase()))
    .sort(natural)
    .map((f) => ({
      file: `assets/photos/${dir}/${f}`,
      group,
      caption: "",
      alt: group === "double" ? "Hum dono" : "Tum",
    }));
}

function run() {
  if (!fs.existsSync(PHOTO_DIR)) fs.mkdirSync(PHOTO_DIR, { recursive: true });

  let entries = [];
  for (const g of GROUPS) entries = entries.concat(scan(g, g));

  // backward compatible: images sitting directly in assets/photos/
  if (!entries.length) {
    entries = fs
      .readdirSync(PHOTO_DIR)
      .filter((f) => EXT.has(path.extname(f).toLowerCase()))
      .sort(natural)
      .map((f) => ({ file: `assets/photos/${f}`, group: "single", caption: "", alt: "Tum" }));
  }

  const js =
    "/* Auto-generated by list-photos.js — DO NOT EDIT BY HAND.\n" +
    "   single/ = her photos, double/ = both of you. */\n" +
    "window.BIRTHDAY_PHOTOS = " +
    JSON.stringify(entries, null, 2) +
    ";\n";

  fs.writeFileSync(OUT_JS, js, "utf8");
  fs.writeFileSync(OUT_JSON, JSON.stringify(entries, null, 2) + "\n", "utf8");

  const single = entries.filter((e) => e.group === "single").length;
  const double = entries.filter((e) => e.group === "double").length;
  console.log(`single: ${single} · double: ${double} · total: ${entries.length}`);
  entries.forEach((e, i) => console.log(`  ${i + 1}. [${e.group}] ${e.file}`));
}

run();
