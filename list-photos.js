/* Scan assets/photos/ -> write photos-data.js + photos.json
   Usage: node list-photos.js
   No dependencies. Works with plain Node 18+. */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const PHOTO_DIR = path.join(ROOT, "assets", "photos");
const OUT_JS = path.join(ROOT, "photos-data.js");
const OUT_JSON = path.join(ROOT, "photos.json");

const EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".heic", ".heif"]);

// natural sort: 2.jpg comes before 10.jpg
const natural = (a, b) =>
  a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

function run() {
  if (!fs.existsSync(PHOTO_DIR)) {
    fs.mkdirSync(PHOTO_DIR, { recursive: true });
    console.log("Created assets/photos/ — drop your photos there and run this again.");
  }

  const files = fs
    .readdirSync(PHOTO_DIR)
    .filter((f) => EXT.has(path.extname(f).toLowerCase()))
    .sort(natural);

  const entries = files.map((file, i) => ({
    file: `assets/photos/${file}`,
    caption: "", // empty -> site uses a caption from config.js
    alt: `Memory ${i + 1}`,
  }));

  const js =
    "/* Auto-generated by list-photos.js — DO NOT EDIT BY HAND.\n" +
    "   Drop images into assets/photos/ and run: node list-photos.js */\n" +
    "window.BIRTHDAY_PHOTOS = " +
    JSON.stringify(entries, null, 2) +
    ";\n";

  fs.writeFileSync(OUT_JS, js, "utf8");
  fs.writeFileSync(OUT_JSON, JSON.stringify(entries, null, 2) + "\n", "utf8");

  console.log(`Found ${entries.length} photo${entries.length === 1 ? "" : "s"}.`);
  if (!entries.length) {
    console.log("Gallery will show pretty placeholders until you add photos.");
  } else {
    entries.forEach((e, i) => console.log(`  ${i + 1}. ${e.file}`));
  }
}

run();
